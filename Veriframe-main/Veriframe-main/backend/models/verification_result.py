import enum
from datetime import datetime
from typing import List, Optional

from pydantic import BaseModel, Field

class Provider(str, enum.Enum):
    REALITY_DEFENDER = "RealityDefender"

class VerificationStatus(str, enum.Enum):
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    INCONCLUSIVE = "INCONCLUSIVE"
    UNSUPPORTED = "UNSUPPORTED"
    ERROR = "ERROR"

class VerificationResult(BaseModel):
    """Immutable result model returned by all verification endpoints.

    It is deliberately minimal – contains only fields that are required by the UI
    and by downstream reporting (Firebase, Firestore). All pipelines must
    construct an instance of this model and return it as JSON.
    """

    verification_id: str = Field(..., description="Unique ID for this verification run")
    verified_at: datetime = Field(default_factory=datetime.utcnow, description="Timestamp of result generation (UTC)")
    provider: Provider = Field(..., description="External forensic provider used for analysis")
    media_type: str = Field(..., description="MIME type or identifier (e.g., 'video/mp4', 'live/stream')")
    source: str = Field(..., description="Human‑readable source description")
    source_url: Optional[str] = Field(None, description="Original URL for link verification or stream URL")
    authenticity_score: Optional[float] = Field(None, ge=0.0, le=100.0, description="Percentage indicating how authentic the media is (100‑authenticity_score = fake probability)")
    fake_probability: Optional[float] = Field(None, ge=0.0, le=100.0, description="Percentage probability that the media is synthetic/manipulated")
    confidence: Optional[float] = Field(None, ge=0.0, le=100.0, description="Overall confidence in the verdict, derived from provider confidence and optional internal metrics")
    verdict: str = Field(..., description="High‑level decision: AUTHENTIC, MANIPULATED, INCONCLUSIVE, UNSUPPORTED, ERROR")
    fine_verdict: Optional[str] = Field(None, description="More granular label when applicable (e.g., REAL, LIKELY_REAL, FAKE, LIKELY_FAKE)")
    risk_level: Optional[str] = Field(None, description="Risk tier: HIGH, MEDIUM, LOW, UNKNOWN")
    evidence: List[str] = Field(default_factory=list, description="Human‑readable list of detected forensic evidence")
    observations: List[str] = Field(default_factory=list, description="Technical observations generated by the pipeline")
    error_code: Optional[str] = Field(None, description="Machine readable error identifier when status is ERROR or UNSUPPORTED")
    metadata_score: Optional[float] = Field(None, description="Quality score of the media container (e.g., resolution, fps) – retained from old pipeline for reporting")
    processing_time_sec: Optional[float] = Field(None, description="Total wall‑clock time spent in the backend for this request")
    report_hash: Optional[str] = Field(None, description="SHA‑256 hash of the report payload for integrity verification")

    class Config:
        allow_mutation = False
        json_encoders = {datetime: lambda v: v.isoformat()}
